/* ============================================================================
 *  font6x8.c  -  Fuente bitmap 6x8 (copiada de EstaticaCX, commit eca703d)
 *
 *  Mapa de caracteres del programa (ver gfx.h): simbolos propios en
 *  0x80-0x9D y Latin-1 en 0xA0-0xFF, como font6x12.c.
 *
 *  Celda de 6x8 con el glifo en 5x7 (la columna 5 y la fila 7 son separacion,
 *  salvo en los descendentes g j p q y , ; y en los subindices).
 *
 *  Los glifos se declaran en ASCII-art, no en hexadecimal: son revisables y
 *  editables de un vistazo, y el coste es solo flash (~7 KB de cadenas const).
 *  En el arranque se compilan a una tabla de bits de 2 KB para que dibujar sea
 *  una simple mascara por fila.
 *
 *  Aqui solo se usa para rotulos del esquema muy apretados; el texto va
 *  con la 6x12 (font6x12.c).
 * ========================================================================= */
