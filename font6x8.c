#define N_GLIFOS ((int)(sizeof GLIFOS / sizeof GLIFOS[0]))

/* Tabla compilada: un byte por fila, bit x = columna x. */
static u8 bits[256][8];
static int listo = 0;

void font_init(void)
{
    int i, y, x, cp;

    if (listo) return;

    for (i = 0; i < 256; i++)
        for (y = 0; y < 8; y++) bits[i][y] = 0;

    for (i = 0; i < N_GLIFOS; i++) {
        cp = GLIFOS[i].cp;
        if (cp < 0 || cp > 255) continue;
        for (y = 0; y < 8; y++) {
            const char *fila = GLIFOS[i].r[y];
            u8 m = 0;
            for (x = 0; x < 5 && fila[x]; x++)
                if (fila[x] != '.') m |= (u8)(1u << x);
            bits[cp][y] = m;
        }
    }

    /* Marcador visible para codigos sin glifo: durante el desarrollo un
     * recuadro delata al instante una etiqueta mal escrita, cosa que un
     * hueco en blanco no haria.                                            */
    for (cp = 0x21; cp <= 0xFF; cp++) {
        int vacio = 1;
        for (y = 0; y < 8; y++) if (bits[cp][y]) { vacio = 0; break; }
        if (vacio) {
            bits[cp][1] = 0x1F; bits[cp][2] = 0x11; bits[cp][3] = 0x11;
            bits[cp][4] = 0x11; bits[cp][5] = 0x11; bits[cp][6] = 0x1F;
        }
    }

    listo = 1;
}

const u8 *font_glifo(unsigned c)
{
    if (!listo) font_init();
    return bits[c & 0xFFu];
}
